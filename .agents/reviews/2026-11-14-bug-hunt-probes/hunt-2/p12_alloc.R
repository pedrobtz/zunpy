# Does a header field alone drive an allocation? (design 12: "Nothing is allocated from a header field")
source("lib.R")
peak <- function(label, expr) {
  invisible(gc(reset = TRUE)); t <- system.time(r <- try1(expr))[["elapsed"]]; g <- gc()
  cat(sprintf("%-46s %s  %.2fs  peak Vcells %.0f MB\n", label, if (r$ok) paste("OK", paste(class(r$v), collapse = "/"), "len", length(r$v)) else paste(r$cls, substr(r$msg, 1, 50)), t, g[2, 6]))
}
peak("baseline <U1 (0,)", npy_decode(mk(H("'<U1'", "(0,)"))))
peak("<U100000000 (0,)  [400 MB item]", npy_decode(mk(H("'<U100000000'", "(0,)"))))
peak("<U536870911 (0,)  [~2 GiB item]", npy_decode(mk(H("'<U536870911'", "(0,)"))))
peak("<U536870912 (0,)  [2 GiB item]", npy_decode(mk(H("'<U536870912'", "(0,)"))))
peak("<U536870913 (0,)", npy_decode(mk(H("'<U536870913'", "(0,)"))))
peak("|S1000000000 (0,) utf8", npy_decode(mk(H("'|S1000000000'", "(0,)"))))
peak("|S1000000000 (0,) latin1", npy_decode(mk(H("'|S1000000000'", "(0,)")), encoding = "latin1"))
peak("|S2147483648 (0,) latin1", npy_decode(mk(H("'|S2147483648'", "(0,)")), encoding = "latin1"))
peak("|V2147483648 (0,)", npy_decode(mk(H("'|V2147483648'", "(0,)"))))
peak("rec [('a','<U100000000')] (0,)", npy_decode(mk(H("[('a', '<U100000000')]", "(0,)"))))
peak("<U100000000 (0,) max_size=1e6", npy_decode(mk(H("'<U100000000'", "(0,)")), max_size = 1e6))
peak("<U249999 (0,) max_size=1e6", npy_decode(mk(H("'<U249999'", "(0,)")), max_size = 1e6))
peak("<U100000000 (0, 5)", npy_decode(mk(H("'<U100000000'", "(0, 5)"))))
peak("|S0 (2147483648,) [zero-width count]", npy_decode(mk(H("'|S0'", "(2147483648,)"))))
peak("|S0 (2147483649,)", npy_decode(mk(H("'|S0'", "(2147483649,)"))))
peak("|S0 (100000000,)  [100M empty strings]", npy_decode(mk(H("'|S0'", "(100000000,)"))))
peak("|V0 (20000000,)  [20M raw(0)]", npy_decode(mk(H("'|V0'", "(20000000,)"))))
peak("[] (50000000,)  [empty record rows]", npy_decode(mk(H("[]", "(50000000,)"))))
peak("[] (2147483647,)", dim(npy_decode(mk(H("[]", "(2147483647,)")))))
peak("[] (2147483648,)", dim(npy_decode(mk(H("[]", "(2147483648,)")))))
peak("[('a','|V0')] (30000000,)", dim(npy_decode(mk(H("[('a', '|V0')]", "(30000000,)")))))
