source("lib.R")
cat("bit64:", requireNamespace("bit64", quietly = TRUE), "\n")
i4 <- function(v) le(as.integer(v), 4)
x <- mk(H("'<i4'", "(4,)"), i4(1:4))
cat("== max_size straddle, raw; length", length(x), "\n")
for (d in c(-1, 0, 1)) show(paste("max_size", length(x) + d), npy_decode(x, max_size = length(x) + d))
f <- tempfile(fileext = ".npy"); writeBin(x, f)
for (d in c(-1, 0, 1)) show(paste("path max_size", length(x) + d), npy_read(f, max_size = length(x) + d))
for (d in c(-1, 0, 1)) show(paste("con max_size", length(x) + d), { con <- rawConnection(x); on.exit(close(con)); npy_read(con, max_size = length(x) + d) })
# u1 file so no fast path
xu <- mk(H("'|u1'", "(4,)"), as.raw(1:4)); writeBin(xu, f)
for (d in c(-1, 0, 1)) show(paste("path(u1) max_size", length(xu) + d), npy_read(f, max_size = length(xu) + d))
cat("== max_size numeric edge\n")
for (m in list(NA, -1, 0, 1.5, Inf, 2^53, 2^53 + 2, NA_integer_, "10", c(1, 2), NULL, TRUE, .Machine$integer.max + 1)) show(paste("max_size", deparse(m)), npy_decode(x, max_size = m))
cat("== max_header straddle\n")
hl <- 118  # 128 - 10
for (d in c(-1, 0, 1)) show(paste("max_header", hl + d), npy_decode(x, max_header = hl + d))
for (d in c(-1, 0, 1)) show(paste("npy_header max_header", hl + d), npy_header(x, max_header = hl + d)$shape)
writeBin(x, f)
for (d in c(-1, 0, 1)) show(paste("npy_header(path) max_header", hl + d), npy_header(f, max_header = hl + d)$shape)
for (d in c(-1, 0, 1)) show(paste("npy_read(path) max_header", hl + d), npy_read(f, max_header = hl + d))
for (m in list(NA, -1, 0, 1.5, Inf, 2^32 - 1, 2^32)) show(paste("max_header", deparse(m)), npy_decode(x, max_header = m))
cat("== max_dims straddle\n")
x3 <- mk(H("'<i4'", "(1, 2, 2)"), i4(1:4))
for (m in list(2, 3, 4, 0, 64, 65, NA, -1)) show(paste("max_dims", deparse(m)), npy_decode(x3, max_dims = m))
show("0-d max_dims 0", npy_decode(mk(H("'<i4'", "()"), i4(7)), max_dims = 0))
for (k in c(31, 32, 33, 63, 64, 65)) {
  xs <- mk(H("'<i4'", paste0("(", paste(rep("1", k), collapse = ", "), ",)")), i4(9))
  show(paste("ndim", k, "default"), length(dim(npy_decode(xs))))
  show(paste("ndim", k, "max_dims=64"), length(dim(npy_decode(xs, max_dims = 64))))
  show(paste("ndim", k, "npy_header"), length(npy_header(xs)$shape))
  writeBin(xs, f); show(paste("ndim", k, "npy_read path"), length(dim(npy_read(f))))
  show(paste("ndim", k, "npy_read path md64"), length(dim(npy_read(f, max_dims = 64))))
}
cat("== max_fields 1024 straddle\n")
for (k in c(1023, 1024, 1025)) {
  d <- paste0("[", paste(sprintf("('c%d', '|u1')", seq_len(k)), collapse = ", "), "]")
  xs <- mk(H(d, "(1,)"), as.raw(seq_len(k) %% 256), ver = 2L)
  show(paste("fields", k), ncol(npy_decode(xs, max_header = 1e6)))
  d <- sprintf("[('a', '|u1', (%d,))]", k)
  xs <- mk(H(d, "(1,)"), as.raw(seq_len(k) %% 256))
  show(paste("subarray cols", k), ncol(npy_decode(xs)))
  d <- sprintf("[('a', '|u1', (%d,)), ('b', '|u1')]", k - 1)
  xs <- mk(H(d, "(1,)"), as.raw(seq_len(k) %% 256))
  show(paste("subarray+1 cols", k), ncol(npy_decode(xs)))
  d <- sprintf("[('a', '|V0', (%d,))]", k)
  show(paste("V0 subarray cols", k), ncol(npy_decode(mk(H(d, "(1,)")))))
  show(paste("V0 subarray cols hdr", k), nrow(npy_header(mk(H(d, "(1,)")))$descr))
}
cat("== nesting depth\n")
for (k in 1:9) {
  s <- paste0(strrep("(", k), "2,", strrep(")", k))   # ((((2,)))) 
  show(paste("shape paren depth", k), npy_decode(mk(H("'<i4'", s), i4(1:2))))
}
cat("== subarray dims 8\n")
for (k in 7:9) {
  d <- sprintf("[('a', '|u1', (%s,))]", paste(rep("1", k), collapse = ", "))
  show(paste("subdims", k), names(npy_decode(mk(H(d, "(2,)"), as.raw(1:2)))))
}
