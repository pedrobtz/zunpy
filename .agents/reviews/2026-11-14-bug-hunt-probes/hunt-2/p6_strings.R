source("lib.R")
u4 <- function(cps, be = FALSE) unlist(lapply(cps, function(cp) { b <- as.raw(c(cp %% 256, (cp %/% 256) %% 256, (cp %/% 65536) %% 256, cp %/% 16777216)); if (be) rev(b) else b }))
enc <- function(v) paste(sprintf("%s[%s|%s]", encodeString(v), Encoding(v), vapply(v, function(s) paste(charToRaw(s), collapse = ""), "")), collapse = " ")
cat("== S\n")
x <- mk(H("'|S4'", "(5,)"), as.raw(c(0x61,0x62,0,0,  0,0,0,0,  0x61,0,0x62,0,  0xc3,0xa9,0,0,  0xe9,0x41,0,0)))
show("S4 utf8 (elt3 has inner NUL)", npy_decode(x))
x <- mk(H("'|S4'", "(4,)"), as.raw(c(0x61,0x62,0,0,  0,0,0,0,   0xc3,0xa9,0,0,  0xe9,0x41,0,0)))
r <- show("S4 utf8 (elt4 invalid)", npy_decode(x))
r <- try1(npy_decode(x, encoding = "latin1")); cat("latin1:", enc(r$v), "\n")
r <- try1(npy_decode(x, encoding = "bytes")); cat("bytes:", enc(r$v), "\n")
r <- try1(npy_decode(x, strings = "raw")); str(r$v)
r <- try1(npy_decode(x, strings = "raw", encoding = "latin1")); cat("raw+latin1 identical to raw:", identical(r$v, npy_decode(x, strings = "raw")), "\n")
x <- mk(H("'|S4'", "(2,)"), as.raw(c(0,0x61,0,0,  0x61,0,0x62,0)))
show("S4 leading NUL", npy_decode(x)); r <- try1(npy_decode(x, strings = "raw")); str(r$v)
show("S4 leading NUL latin1", npy_decode(x, encoding = "latin1")); show("S4 leading NUL bytes", npy_decode(x, encoding = "bytes"))
show("S0 (3,)", npy_decode(mk(H("'|S0'", "(3,)")))); show("S0 raw", npy_decode(mk(H("'|S0'", "(3,)")), strings = "raw"))
show("V0 (3,)", npy_decode(mk(H("'|V0'", "(3,)")))); show("U0 (3,)", npy_decode(mk(H("'<U0'", "(3,)"))))
