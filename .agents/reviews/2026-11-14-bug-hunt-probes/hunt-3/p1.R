w <- function(.n, x, ...) {
  r <- tryCatch(npy_encode(x, ...), error = function(e) { cat(.n, "ERR:", conditionMessage(e), "\n"); NULL })
  if (!is.null(r)) writeBin(r, file.path("out1", paste0(.n, ".npy")))
}
