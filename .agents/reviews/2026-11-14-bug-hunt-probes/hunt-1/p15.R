source("h.R")
u <- function(s) { Encoding(s) <- "UTF-8"; s }
d <- function(descr, shape="(2,)", fo="False") sprintf("{'descr': %s, 'fortran_order': %s, 'shape': %s, }", descr, fo, shape)
n8 <- u("caf\xc3\xa9"); nl <- "caf\xe9"; Encoding(nl) <- "latin1"
b <- npy_encode(setNames(list(1, 2), c(n8, "b")))
T("names= latin1-marked selects utf8 member", names(npy_decode(b, names = nl)))
T("result name encoding", Encoding(names(npy_decode(b, names = nl))))
T("npz list $ access", npy_decode(b)[[n8]])
T("struct strings=raw", str(npy_decode(mk(d("[('s', '|S2'), ('v', '|V1')]"), as.raw(c(65,66,1,67,0,2))), strings = "raw")))
T("struct S", str(npy_decode(mk(d("[('s', '|S2'), ('v', '|V1')]"), as.raw(c(65,66,1,67,0,2))))))
T("subarray", str(npy_decode(mk(d("[('a', '<i4', (2,)), ('b', '|u1')]", "(1,)"), c(writeBin(1:2, raw(), endian="little"), as.raw(9))))))
T("subarray re-encode hdr", npy_header(npy_encode(npy_decode(mk(d("[('a', '<i4', (2,)), ('b', '|u1')]", "(1,)"), c(writeBin(1:2, raw(), endian="little"), as.raw(9))))))$descr[,c(1,3)])
T("subarray clash", npy_decode(mk(d("[('a', '<i4', (2,)), ('a.1', '|u1')]", "(1,)"), c(writeBin(1:2, raw(), endian="little"), as.raw(9)))))
con <- file("out/two.bin", "wb"); writeBin(c(npy_encode(1:3), npy_encode(c(2.5, 3.5))), con); close(con)
T("con sequential", {con <- file("out/two.bin", "rb"); on.exit(close(con)); h <- npy_header(con); list(h$shape, tryCatch(npy_read(con), error=function(e) conditionMessage(e)))})
T("con text open", {con <- file("out/m.npy", "r"); on.exit(close(con)); npy_read(con)})
T("rawConnection", {con <- rawConnection(npy_encode(1:3)); on.exit(close(con)); npy_read(con)})
T("write rawConnection", {con <- rawConnection(raw(), "wb"); npy_write(1:3, con); r <- rawConnectionValue(con); close(con); identical(r, npy_encode(1:3))})
T("write returns invisibly the con", {con <- rawConnection(raw(), "wb"); r <- npy_write(1:3, con); close(con); class(r)})
T("write ''", npy_write(1, ""))
T("write url", npy_write(1, "http://127.0.0.1:9/x.npy"))
T("write tilde/unicode path", {p <- file.path("out", u("caf\xc3\xa9.npy")); npy_write(1:2, p); npy_read(p)})
T("npy_write list no names", npy_write(list(1), "out/x.npz"))
T("write append semantic: overwrites", {p <- "out/ow.npy"; npy_write(1:1000, p); npy_write(1L, p); file.size(p)})
