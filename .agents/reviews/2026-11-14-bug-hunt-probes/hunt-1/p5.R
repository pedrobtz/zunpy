T("<M8[s]", npy_decode(mk(d("'<M8[s]'"), i8)))
T("m8[D] native", npy_decode(mk(d("'m8[D]'"), i8)))
T("header i8", npy_header(mk(d("'i8'"), i8))$descr)
T("<M8 generic", npy_decode(mk(d("'<M8'"), i8)))
T("<M8[5s]", npy_decode(mk(d("'<M8[5s]'"), i8)))
