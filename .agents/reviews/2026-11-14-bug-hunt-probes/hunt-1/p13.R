source("h.R")
suppressMessages(library(bit64))
le8 <- function(v) unlist(lapply(v, function(z) writeBin(as.integer(c(z %% 2^32, z %/% 2^32)), raw(), size=4, endian="little")))
be8 <- function(v) unlist(lapply(v, function(z) rev(le8(z))))
d <- function(descr, shape="(2,)", fo="False") sprintf("{'descr': %s, 'fortran_order': %s, 'shape': %s, }", descr, fo, shape)
nat <- as.raw(c(0,0,0,0,0,0,0,0x80))
x <- T("<M8[h] dec", npy_decode(mk(d("'<M8[h]'"), c(le8(5), nat))))
T("<M8[h] re-encode", {b <- npy_encode(x); list(npy_header(b)$descr, identical(b[-(1:128)], c(le8(5), nat)))})
y <- T(">M8[h] dec", npy_decode(mk(d("'>M8[h]'"), be8(c(5, 7)))))
T(">M8[h] re-encode", {b <- npy_encode(y); npy_header(b)$descr})
y <- T(">M8[s] datetime=integer64", npy_decode(mk(d("'>M8[s]'"), be8(c(5, 7))), datetime="integer64"))
T(">M8[s] i64 re-encode", {b <- npy_encode(y); list(npy_header(b)$descr, npy_decode(b))})
y <- T(">m8[Y] struct", npy_decode(mk(d("[('a', '>m8[Y]')]"), be8(c(5, 7)))))
T(">m8[Y] struct re-encode", npy_header(npy_encode(y))$descr$descr)
y <- T("<M8[s] datetime=integer64", npy_decode(mk(d("'<M8[s]'"), c(le8(5), nat)), datetime="integer64"))
T("  re-encode", {b <- npy_encode(y); list(npy_header(b)$descr, npy_decode(b))})
T("  re-encode dtype override", npy_header(npy_encode(y, dtype="<M8[ms]"))$descr)
T("  re-encode dtype i8", npy_header(npy_encode(y, dtype="<i8"))$descr)
T("  subset keeps?", {z <- y[1]; list(attributes(z), tryCatch(npy_header(npy_encode(z))$descr, error=function(e) conditionMessage(e)))})
T("  c() ", {z <- c(y, y); list(attributes(z), tryCatch(npy_header(npy_encode(z))$descr, error=function(e) conditionMessage(e)))})
T("npy_dtype(y)", npy_dtype(y))
T("forged npy_dtype", npy_encode(structure(as.integer64(1), npy_dtype="<M8[zz]")))
T("forged npy_dtype 2", npy_header(npy_encode(structure(as.integer64(1), npy_dtype=c("<M8[s]","x"))))$descr)
T("forged npy_dtype 3", npy_header(npy_encode(structure(as.integer64(1), npy_dtype="<M8[5s]")))$descr)
# datetime=integer64 for units with R class in df
T("m8 convert vs i64", {b <- mk(d("'<m8[ms]'"), le8(c(1500, 3))); list(npy_decode(b), npy_decode(b, datetime="integer64"))})
# POSIXct property
set.seed(1)
t0 <- round(runif(20000, -2e9, 4e9) * 1e6) / 1e6
ct <- as.POSIXct(t0, origin="1970-01-01", tz="UTC")
r <- T("POSIXct us property", {b <- npy_encode(ct); writeBin(b, "out/ct.npy"); writeBin(t0, "out/ct.f8", endian="little"); identical(npy_decode(b), ct)})
t1 <- round(runif(20000, -2e9, 4e9) * 1e3) / 1e3
T("POSIXct ms property", {ct <- as.POSIXct(t1, origin="1970-01-01", tz="UTC"); identical(npy_decode(npy_encode(ct, unit="ms")), ct)})
T("POSIXct ms as us", {ct <- as.POSIXct(t1, origin="1970-01-01", tz="UTC"); identical(npy_decode(npy_encode(ct)), ct)})
T("POSIXct us as ns", {identical(npy_decode(npy_encode(ct[1:100], unit="ns")), ct[1:100])})
T("Sys.time", {s <- Sys.time(); r <- npy_decode(npy_encode(s)); unclass(r) == unclass(s)})
T("difftime us prop", {x <- as.difftime(round(runif(20000, -1e6, 1e6)*1e6)/1e6, units="secs"); identical(npy_decode(npy_encode(x, dtype="<m8[us]")), x)})
T("difftime mins->ms", {x <- as.difftime(c(0.1, 1/3), units="mins"); tryCatch(npy_decode(npy_encode(x, dtype="<m8[ms]")), error=function(e) conditionMessage(e))})
T("Date matrix", {x <- structure(c(1,2,3,4), class="Date", dim=c(2L,2L)); npy_decode(npy_encode(x))})
T("Date int NA", npy_decode(npy_encode(structure(c(1L, NA), class="Date"))))
T("Date big", npy_encode(structure(2^62, class="Date")))
T("POSIXct list-ish", npy_encode(as.POSIXlt(Sys.time())))
