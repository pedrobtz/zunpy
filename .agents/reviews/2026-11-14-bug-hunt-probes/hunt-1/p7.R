routes <- function(f, ...) {
  a <- tryCatch(npy_read(f, ...), error = function(e) paste("ERR", class(e)[1], conditionMessage(e)))
  con <- file(f, "rb"); b <- tryCatch(npy_read(con, ...), error = function(e) paste("ERR", class(e)[1], conditionMessage(e))); close(con)
  c2 <- tryCatch(npy_read(file(f), ...), error = function(e) paste("ERR", class(e)[1], conditionMessage(e)))
  d <- tryCatch(npy_decode(readBin(f, "raw", file.size(f)), ...), error = function(e) paste("ERR", class(e)[1], conditionMessage(e)))
  u <- tryCatch(npy_read(paste0("file://", normalizePath(f)), ...), error = function(e) paste("ERR", class(e)[1], conditionMessage(e)))
  ok <- identical(a, b) && identical(a, c2) && identical(a, d) && identical(a, u)
  cat(sprintf("routes %-22s %s  -> %s\n", basename(f), paste(names(list(...)), unlist(list(...)), collapse=","), if (ok) "ALL SAME" else "DIFFER"))
  if (!ok) { str(a); str(b); str(c2); str(d); str(u) }
  invisible(a)
}
