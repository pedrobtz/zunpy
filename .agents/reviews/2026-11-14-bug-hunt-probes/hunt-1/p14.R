le8 <- function(v) unlist(lapply(v, function(z) writeBin(as.integer(c(z %% 2^32, z %/% 2^32)), raw(), size=4, endian="little")))
be8 <- function(v) unlist(lapply(v, function(z) rev(le8(z))))
d <- function(descr, shape="(2,)", fo="False") sprintf("{'descr': %s, 'fortran_order': %s, 'shape': %s, }", descr, fo, shape)
y <- npy_decode(mk(d("'>M8[h]'"), be8(c(5, 7)))); T("attr >M8[h]", attributes(y))
T("npy_dtype(>)", npy_dtype(y))
T("npy_header >M8[h]", npy_header(mk(d("'>M8[h]'"), be8(c(5, 7))))$descr)
T("Date matrix attrs", attributes(npy_decode(npy_encode(structure(c(1,2,3,4), class="Date", dim=c(2L,2L))))))
T("POSIXct matrix attrs", attributes(npy_decode(npy_encode(structure(c(1,2,3,4), class=c("POSIXct","POSIXt"), dim=c(2L,2L))))))
T("i64 matrix C order", {x <- bit64::as.integer64(1:6); dim(x) <- c(2,3); r <- npy_decode(npy_encode(x, order="C"), int64="integer64"); identical(unclass(r), unclass(x))})
T("hdr huge shape", sprintf("%.0f", npy_header(mk(d("'<f8'", "(9007199254740993,)")))$shape))
T("hdr huge shape 2^63", sprintf("%.0f", npy_header(mk(d("'<f8'", "(9223372036854775808,)")))$shape))
T("hdr huge shape 2^53", sprintf("%.0f", npy_header(mk(d("'<f8'", "(9007199254740992, 2)")))$shape))
T("hdr itemsize U", npy_header(npy_encode(c("a","bbb")))$itemsize)
T("hdr v3", npy_header(npy_encode(setNames(data.frame(1), "日")))$version)
T("hdr path v2", {b <- mk(d("'<f8'"), writeBin(c(1,2), raw()), ver=2); writeBin(b, "out/v2h.npy"); identical(npy_header("out/v2h.npy"), npy_header(b))})
T("hdr path short v2", {writeBin(mk(d("'<f8'"), raw(), ver=2)[1:11], "out/v2s.npy"); npy_header("out/v2s.npy")})
T("hdr path ver0", {b <- mk(d("'<f8'"), raw()); b[7] <- as.raw(0); writeBin(b, "out/v0.npy"); c(tryCatch(npy_header("out/v0.npy"), error=function(e) conditionMessage(e)), tryCatch(npy_header(b), error=function(e) conditionMessage(e)))})
T("hdr path ver4", {b <- mk(d("'<f8'"), raw()); b[7] <- as.raw(4); writeBin(b, "out/v4.npy"); c(tryCatch(npy_header("out/v4.npy"), error=function(e) conditionMessage(e)), tryCatch(npy_header(b), error=function(e) conditionMessage(e)))})
T("hdr data frame struct shape col", npy_header(npy_encode(data.frame(a=1:2, b=c("x","y"))))$descr)
# data_offset vs reality
T("data_offset real", {b <- npy_encode(c(1.5, 2.5)); h <- npy_header(b); identical(readBin(b[(h$data_offset+1):length(b)], "double", 2), c(1.5, 2.5))})
# big header -> v2
