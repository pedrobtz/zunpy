source("h.R")
u <- function(s) { Encoding(s) <- "UTF-8"; s }
l <- list(a = 1:3, ab = c(1.5, 2), `a.npy` = "x", df = data.frame(p = 1:2, q = c("u", "vv")), m = matrix(1:6, 2), d = as.Date("2024-01-01"))
b <- npy_encode(l); writeBin(b, "out/l.npz"); bc <- npy_encode(l, compress = TRUE); writeBin(bc, "out/lc.npz")
T("npz rt", {r <- npy_decode(b); str(r); identical(r, npy_decode(bc))})
T("npy_names", npy_names(b)); T("npy_names path", npy_names("out/l.npz")); T("npy_names con", npy_names(file("out/l.npz")))
T("names sel", names(npy_decode(b, names = c("ab", "a", "ab"))))
T("names partial", npy_decode(b, names = "d"))
T("names 'a' exact", npy_decode(b, names = "a"))
T("names empty", npy_decode(b, names = character()))
T("names NA", npy_decode(b, names = NA_character_))
T("names num", npy_decode(b, names = 1))
T("names missing", npy_decode(b, names = "zz"))
T("names factor", npy_decode(b, names = factor("a")))
T("names with .npy", names(npy_decode(b, names = "a.npy")))
T("read names", names(npy_read("out/l.npz", names = "m")))
T("read names partial n=", npy_read("out/l.npz", n = "m"))
T("member vs lone", identical(npy_decode(b)$m, npy_decode(npy_encode(l$m))))
T("lone bytes == member bytes", {mm <- npy_encode(l$m); i <- which(b == mm[1]); any(vapply(i, function(k) identical(b[k:(k+length(mm)-1)], mm), NA))})
T("npz dtype list", npy_header(npy_decode(npy_encode(list(a=1:3, ab=1:2), dtype=list(a="<i8")), names="a")$a |> npy_encode())$descr)
T("npz dtype applies", {bb <- npy_encode(list(a=1:3, ab=1:2), dtype=list(ab="|u1")); writeBin(bb, "out/dt.npz"); 1})
T("npz dtype chr vec", npy_encode(list(a=1:3), dtype=c(a="<i8")))
T("npz dtype unnamed", npy_encode(list(a=1:3), dtype=list("<i8")))
T("npz dtype unknown", npy_encode(list(a=1:3), dtype=list(b="<i8")))
T("npz dtype df member", npy_header(npy_decode(npy_encode(list(df=data.frame(p=1:2)), dtype=list(df=c(p="<i8"))))$df |> npy_encode())$descr$descr)
T("npz na allow", npy_decode(npy_encode(list(a=c(1L,NA)), na="allow"), na="allow"))
T("npz err member", tryCatch(npy_encode(list(ok=1, bad=c(1L,NA))), error=function(e) list(conditionMessage(e), e$member, e$index, class(e))))
T("npz dec err member", tryCatch(npy_decode(npy_encode(list(ok=1, bad=c(1L,NA)), na="allow")), error=function(e) list(conditionMessage(e), e$member, e$index, class(e)[1])))
T("npz nested", npy_encode(list(a=list(b=1))))
T("npz names bad /", npy_encode(list(`a/b`=1)))
T("npz names ..", npy_encode(list(`..a`=1)))
T("npz names .", npy_encode(list(`.`=1)))
T("npz names bs", npy_encode(setNames(list(1), "a\\b")))
T("npz name NA", npy_encode(setNames(list(1), NA)))
T("npz name empty some", npy_encode(list(a=1, 2)))
T("npz empty list named", {e <- npy_encode(structure(list(), names=character())); writeBin(e, "out/empty.npz"); npy_decode(e)})
T("npz name utf8", {n <- u("caf\xc3\xa9 \xe6\x97\xa5"); e <- npy_encode(setNames(list(1), n)); writeBin(e, "out/u.npz"); identical(names(npy_decode(e)), n)})
T("npz name newline/space", {e <- npy_encode(setNames(list(1, 2), c("a b", "c\nd"))); writeBin(e, "out/sp.npz"); names(npy_decode(e))})
T("npz long name", {e <- npy_encode(setNames(list(1), strrep("x", 65531))); nchar(names(npy_decode(e)))})
T("npz too long name", npy_encode(setNames(list(1), strrep("x", 65532))))
T("npz compress non-list", npy_encode(1, compress=TRUE))
T("npz compress NA", npy_encode(list(a=1), compress=NA))
T("npz compress 'yes'", npy_encode(list(a=1), compress="TRUE"))
T("npz max_members", npy_decode(b, max_members = 2))
T("npz max_members names", npy_decode(b, names="a", max_members = 2))
T("npy_names max_members", npy_names(b, max_members = 2))
T("npz max_size", npy_decode(b, max_size = 100))
T("npz write/read", {npy_write(l, "out/w.npz"); identical(npy_read("out/w.npz"), npy_decode(b))})
T("npz write compress", {npy_write(l, "out/wc.npz", compress=TRUE); identical(npy_read("out/wc.npz"), npy_decode(b))})
T("npz read con", identical(npy_read(file("out/w.npz")), npy_decode(b)))
T("npy_names of npy", npy_names(npy_encode(1)))
T("npz deterministic", identical(npy_encode(l), b))
T("POSIXlt list", names(npy_decode(npy_encode(unclass(as.POSIXlt("2024-01-02 03:04:05", tz="UTC"))))))
T("big npz member count", {x <- setNames(as.list(1:300), paste0("k", 1:300)); r <- npy_decode(npy_encode(x)); identical(r, x)})
